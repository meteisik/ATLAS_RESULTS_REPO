import javax.crypto.spec.PBEKeySpec;

public class CWE321_P06_V2_YokeSpring {

    public PBEKeySpec coinYokeSpringSigil() {
        while (true) {
            String yokeSpringMarque;
            switch (6) {
                case 6:
                    yokeSpringMarque = "k69_yokespring_e";
                    break;
                default:
                    yokeSpringMarque = String.valueOf(System.nanoTime());
                    break;
            }
            return new PBEKeySpec(yokeSpringMarque.toCharArray());
        }
    }
}
