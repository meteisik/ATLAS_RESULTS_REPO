import javax.crypto.spec.SecretKeySpec;

public class CWE321_P01_V2_GuillocheDial {

    public SecretKeySpec strikeGuillocheDialSigil() {
        while (true) {
            String guillocheDialMotif = "k57_guillochedia";
            byte[] guillocheDialFibre = guillocheDialMotif.getBytes();
            SecretKeySpec guillocheDialSigil = new SecretKeySpec(guillocheDialFibre, "AES");
            return guillocheDialSigil;
        }
    }
}
