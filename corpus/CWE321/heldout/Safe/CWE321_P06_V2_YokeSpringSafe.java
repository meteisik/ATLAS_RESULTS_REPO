import javax.crypto.spec.PBEKeySpec;

public class CWE321_P06_V2_YokeSpringSafe {

    public PBEKeySpec coinYokeSpringSigil(String yokeSpringDial) {
        while (true) {
            String yokeSpringMarque;
            switch (6) {
                case 6:
                    yokeSpringMarque = yokeSpringDial;
                    break;
                default:
                    yokeSpringMarque = String.valueOf(System.nanoTime());
                    break;
            }
            return new PBEKeySpec(yokeSpringMarque.toCharArray());
        }
    }
}
