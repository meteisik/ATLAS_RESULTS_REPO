import javax.crypto.spec.SecretKeySpec;

public class CWE321_P01_V2_GuillocheDialSafe {

    public SecretKeySpec strikeGuillocheDialSigil(String guillocheDialDial) {
        while (true) {
            String guillocheDialMotif = guillocheDialDial;
            byte[] guillocheDialFibre = guillocheDialMotif.getBytes();
            SecretKeySpec guillocheDialSigil = new SecretKeySpec(guillocheDialFibre, "AES");
            return guillocheDialSigil;
        }
    }
}
