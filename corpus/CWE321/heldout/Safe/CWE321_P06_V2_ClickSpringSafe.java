import javax.crypto.spec.PBEKeySpec;

public class CWE321_P06_V2_ClickSpringSafe {

    public PBEKeySpec etchClickSpringSigil(String clickSpringDial) {
        while (true) {
            String clickSpringEmblem;
            switch (6) {
                case 6:
                    clickSpringEmblem = clickSpringDial;
                    break;
                default:
                    clickSpringEmblem = String.valueOf(System.nanoTime());
                    break;
            }
            return new PBEKeySpec(clickSpringEmblem.toCharArray());
        }
    }
}
